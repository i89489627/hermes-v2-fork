#: ``gepa`` availability probe — optional dependency, never imported (see
#: module docstring). Swapping the built-in OptimizationLoop for the library
#: later is an implementation detail behind :meth:`GEPARunner.run_weekly`.
HAS_GEPA: Final[bool] = importlib.util.find_spec("gepa") is not None

#: Minimum evaluated candidates the loop must produce per component
#: (plan P10.T5 acceptance: ">=3 candidates per component").
_MIN_CANDIDATES_PER_COMPONENT: Final[int] = 3

#: Eval-set record schema: ``{input, expected_output, context}`` (P10.T2
#: fixtures); the adapter's injected runner consumes the record verbatim.
_REQUIRED_EXAMPLE_KEYS: Final[frozenset[str]] = frozenset(
    {"input", "expected_output"}
)

#: Reflective rewriter seam: ``model_factory(component) -> (text -> prompt)``
#: — the gepa reflection-LM role. ``None`` selects the deterministic mutator.
ReflectiveRewriterFactory = Callable[[str], Callable[[str], str]]


def default_prompt_template_path(component: str) -> Path:
    """Default deployment surface: ``<hermes_home>/optimization/prompts/<component>.txt``.

    The pipeline reads this file at cron time (P10.T6); a
    :class:`ComponentSpec` without an explicit ``prompt_template_path``
    deploys here.
    """
    return hermes_home() / "optimization" / "prompts" / f"{component}.txt"


@dataclass(frozen=True)
class ComponentSpec:
    """One optimized component: adapter + eval set + deployment surface."""

    component: str
    adapter: BaseAdapter
    eval_set_path: Path
    prompt_template_path: Path | None = None

    def resolve_template_path(self) -> Path:
        """The template file to seed from and deploy to (default path when unset)."""
        if self.prompt_template_path is not None:
            return Path(self.prompt_template_path)
        return default_prompt_template_path(self.component)


@dataclass(frozen=True)
class DeploymentRecord:
    """One deployment event (the ``on_deploy`` hook payload).

    ``version_id`` is content-addressed (sha256 of the deployed prompt), so
    re-deploying an identical prompt yields the same id.
    ``generation`` is the loop generation the deployed candidate was produced
    in — ``0`` for the seed or for a candidate inherited from a previous
    run's Pareto front.
    """

    component: str
    version_id: str
    prompt: str
    score: float
    generation: int
    run_id: str
    deployed_at: str


@dataclass(frozen=True)
class OptimizationResult:
    """Outcome of one :meth:`GEPARunner.run_weekly` invocation.

    ``candidates_per_component`` counts ALL candidates evaluated during the
    run (seed included); ``deployed`` maps component -> the prompt text that
    was written to its template file (== the Pareto-front best).
    """

    components_run: list[str]
    candidates_per_component: dict[str, int]
    deployed: dict[str, str]
    elapsed_seconds: float
    run_id: str


class GEPARunner:
    """Orchestrates weekly offline GEPA runs over the memory components (plan P10.T5).

    ``components`` maps component name -> :class:`ComponentSpec` (a sequence
    is accepted and keyed by ``spec.component``). ``trace_store`` receives a
    summary trace per component run (observability; the P11.T1 schema has no
    dedicated optimization stage, so the summary rides the ``extraction``
    payload slot). ``pareto`` defaults to a store at the default persistence
    path; ``git`` (optional) is a :class:`GitBackend` whose repository
    contains the prompt templates / Pareto store — every deployment is
    committed there for the audit trail. ``on_deploy`` (optional) is the
    drift-registry hook invoked with the :class:`DeploymentRecord` after each
    deployment.
    """

    def __init__(
        self,
        components: Mapping[str, ComponentSpec] | Sequence[ComponentSpec],
        trace_store: TraceStore | None = None,
        pareto: ParetoFrontStore | None = None,
        model_factory: ReflectiveRewriterFactory | None = None,
        git: GitBackend | None = None,
        on_deploy: Callable[[DeploymentRecord], None] | None = None,
        n_generations: int = 3,
        variants_per_generation: int = 3,
        top_k: int = 3,
    ) -> None:
        if isinstance(n_generations, bool) or n_generations < 1:
            raise ValueError(f"n_generations must be >= 1, got {n_generations!r}")
        if isinstance(variants_per_generation, bool) or variants_per_generation < 1:
            raise ValueError(
                f"variants_per_generation must be >= 1, got {variants_per_generation!r}"
            )
        if isinstance(top_k, bool) or top_k < 1:
            raise ValueError(f"top_k must be >= 1, got {top_k!r}")

        specs: dict[str, ComponentSpec] = {}
        if isinstance(components, Mapping):
            items: list[tuple[str, ComponentSpec]] = list(components.items())
        else:
            items = [(spec.component, spec) for spec in components]
        if not items:
            raise ValueError("components must contain at least one ComponentSpec")
        for name, spec in items:
            if not isinstance(name, str) or not name.strip():
                raise ValueError("component names must be non-empty strings")
            if not isinstance(spec, ComponentSpec):
                raise TypeError(
                    f"components[{name!r}] must be a ComponentSpec, "
                    f"got {type(spec).__name__}"
                )
            if not isinstance(spec.adapter, BaseAdapter):
                raise TypeError(
                    f"components[{name!r}].adapter must be a BaseAdapter, "
                    f"got {type(spec.adapter).__name__}"
                )
            if name in specs:
                raise ValueError(f"duplicate component name: {name!r}")
            specs[name] = spec

        self.components: dict[str, ComponentSpec] = specs
        self.trace_store = trace_store
        self.pareto = pareto if pareto is not None else ParetoFrontStore()
        self.model_factory = model_factory
        self.git = git
        self.on_deploy = on_deploy
        self.n_generations = n_generations
        self.variants_per_generation = variants_per_generation
        self.top_k = top_k
        self._rewriters: dict[str, Callable[[str], str]] = {}

    # ── weekly orchestration ──────────────────────────────────────────────
    def run_weekly(
        self,
        components: str | Collection[str] | None = None,
        now: datetime | None = None,
    ) -> OptimizationResult:
        """Run the optimization loop for the selected components and deploy.

        ``components`` selects a subset (a single name or a collection);
        ``None`` runs every configured component. ``now`` pins the run id and
        trace timestamps (naive datetimes are interpreted as UTC). Per
        component: load the eval set, seed from the current prompt template,
        run the OptimizationLoop, add every evaluated candidate to the Pareto
        front, deploy the front's best to the template file, fire the
        ``on_deploy`` hook, commit the audit trail, and append a summary
        trace.
        """
        started = time.monotonic()
        run_now = _resolve_now(now)
        run_id = f"gepa-{run_now:%Y%m%dT%H%M%SZ}"

        components_run: list[str] = []
        candidates_per_component: dict[str, int] = {}
        deployed: dict[str, str] = {}
        for name in self._select(components):
            count, prompt = self._optimize_component(
                self.components[name], run_id, run_now
            )
            components_run.append(name)
            candidates_per_component[name] = count
            deployed[name] = prompt
        return OptimizationResult(
            components_run=components_run,
            candidates_per_component=candidates_per_component,
            deployed=deployed,
            elapsed_seconds=time.monotonic() - started,
            run_id=run_id,
        )

    def _select(self, components: str | Collection[str] | None) -> list[str]:
        """Resolve the ``components`` selection to a deduplicated name order."""
        if components is None:
            return list(self.components)
        selected = [components] if isinstance(components, str) else list(components)
        unknown = [name for name in selected if name not in self.components]
        if unknown:
            raise KeyError(
                f"unknown component(s) {unknown!r}; configured: {sorted(self.components)}"
            )
        seen: set[str] = set()
        ordered: list[str] = []
        for name in selected:
            if name not in seen:
                seen.add(name)
                ordered.append(name)
        return ordered

    # ── the OptimizationLoop (built-in GEPA-style loop) ───────────────────
    def _optimize_component(
        self, spec: ComponentSpec, run_id: str, run_now: datetime
    ) -> tuple[int, str]:
        """Run one component end-to-end; returns (candidate count, deployed prompt)."""
        examples = _load_eval_set(spec.eval_set_path)
        template_path = spec.resolve_template_path()
        seed_prompt = _read_template(template_path, spec.component)

        evaluated: dict[str, tuple[float, str]] = {}
        generation_of: dict[str, int] = {}

        def evaluate(prompt: str, generation: int) -> tuple[float, str]:
            """Evaluate once, record on the Pareto front, cache by prompt text."""
            cached = evaluated.get(prompt)
            if cached is not None:
                return cached
            score, feedback = spec.adapter.evaluate(prompt, examples)
            evaluated[prompt] = (score, feedback)
            generation_of.setdefault(prompt, generation)
            self.pareto.add_candidate(spec.component, prompt, {"score": score})
            return (score, feedback)

        seed_score, _seed_feedback = evaluate(seed_prompt, generation=0)
        pool: list[tuple[float, str]] = [(seed_score, seed_prompt)]

        for generation in range(1, self.n_generations + 1):
            # Top-K survivors, deterministic order; rotate the mutation base
            # through the pool for exploration while always keeping the best.
            pool.sort(key=lambda item: (-item[0], item[1]))
            base_prompt = pool[(generation - 1) % len(pool)][1]
            base_feedback = evaluated[base_prompt][1]
            batch = spec.adapter.evaluate_batch(base_prompt, examples)
            notes = spec.adapter.make_reflective_dataset(batch)
            rewriter = self._rewriter_for(spec.component)

            for variant_index in range(1, self.variants_per_generation + 1):
                candidate = _deterministic_mutation(
                    base_prompt, notes, generation, variant_index
                )
                if rewriter is not None:
                    rewritten = _model_rewrite(
                        rewriter,
                        spec.component,
                        base_feedback,
                        notes,
                        generation,
                        variant_index,
                        base_prompt,
                    )
                    if rewritten is not None:
                        candidate = rewritten
                score, _feedback = evaluate(candidate, generation)
                pool.append((score, candidate))
            pool.sort(key=lambda item: (-item[0], item[1]))
            pool = pool[: self.top_k]

        candidate_count = len(evaluated)
        if candidate_count < _MIN_CANDIDATES_PER_COMPONENT:
            raise RuntimeError(
                f"optimization produced {candidate_count} candidates for "
                f"{spec.component!r}; the plan requires >= "
                f"{_MIN_CANDIDATES_PER_COMPONENT}"
            )

        # Deploy the Pareto-front best (which may be a candidate inherited
        # from a previous run's front; generation 0 marks those).
        best = self.pareto.get_best(spec.component)
        deployed_prompt = best.prompt
        deployed_score = best.mean_score()
        generation = generation_of.get(deployed_prompt, 0)
        _atomic_write_text(template_path, deployed_prompt)
        record = DeploymentRecord(
            component=spec.component,
            version_id=_version_id_for(spec.component, deployed_prompt),
            prompt=deployed_prompt,
            score=deployed_score,
            generation=generation,
            run_id=run_id,
            deployed_at=run_now.isoformat(),
        )
        if self.on_deploy is not None:
            self.on_deploy(record)
        self._audit_commit(spec, template_path, record)
        self._record_run_trace(spec, record, len(examples), run_now)
        return candidate_count, deployed_prompt

    # ── hooks ─────────────────────────────────────────────────────────────
    def _rewriter_for(self, component: str) -> Callable[[str], str] | None:
        """Component rewriter from ``model_factory`` (cached), or None."""
        if self.model_factory is None:
            return None
        rewriter = self._rewriters.get(component)
        if rewriter is None:
            built = self.model_factory(component)
            if not callable(built):
                raise TypeError(
                    f"model_factory({component!r}) must return a callable, "
                    f"got {type(built).__name__}"
                )
            rewriter = built
            self._rewriters[component] = rewriter
        return rewriter

    def _audit_commit(
        self, spec: ComponentSpec, template_path: Path, record: DeploymentRecord
    ) -> None:
        """Commit the deployment to the audit repo: ``[gepa] deploy ...`` (plan Phase 10)."""
        if self.git is None:
            return
        files = [
            candidate
            for candidate in (template_path, self.pareto.path)
            if _inside_dir(candidate, self.git.repo_path)
        ]
        if not files:
            # Nothing under the audit repository: the deployment is still
            # recorded via the returned OptimizationResult, the on_deploy
            # hook and the summary trace.
            return
        self.git.commit(
            f"[gepa] deploy {spec.component} {record.generation} "
            f"score={record.score:.4f}",
            files,
        )

    def _record_run_trace(
        self,
        spec: ComponentSpec,
        record: DeploymentRecord,
        n_examples: int,
        run_now: datetime,
    ) -> None:
        """Append one summary trace per component run (observability only)."""
        if self.trace_store is None:
            return
        self.trace_store.append(
            Trace(
                # The run summary is idempotent per (run, component): the
                # trace id IS the deterministic turn id, so a re-run of the
                # same pinned run upserts instead of duplicating.
                trace_id=f"{record.run_id}-{spec.component}",
                turn_id=f"{record.run_id}-{spec.component}",
                session_id="gepa-runner",
                timestamp=run_now.timestamp(),
                user_prompt=f"[gepa] weekly optimization for component {spec.component}",
                models_used=["gepa-runner"],
                extraction={
                    "event": "gepa_weekly_run",
                    "component": spec.component,
                    "deployed_version_id": record.version_id,
                    "score": record.score,
                    "generation": record.generation,
                    "eval_examples": n_examples,
                    "prompt_chars": len(record.prompt),
                },
            )
        )


# ── module-level helpers ──────────────────────────────────────────────────────


def _resolve_now(now: datetime | None) -> datetime:
    """``now`` or the current time; naive datetimes are interpreted as UTC."""
    if now is None:
        return datetime.now(UTC)
    if now.tzinfo is None:
        return now.replace(tzinfo=UTC)
    return now


def _load_eval_set(path: Path) -> list[dict[str, Any]]:
    """Load ``{input, expected_output, context}`` records from a P10.T2 fixture."""
    if not path.is_file():
        raise FileNotFoundError(f"eval set not found: {path}")
    doc: Any = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(doc, dict) or not isinstance(doc.get("examples"), list):
        raise ValueError(
            f"eval set {path} must be a JSON object with an 'examples' list"
        )
    examples: list[dict[str, Any]] = []
    for index, raw in enumerate(doc["examples"]):
        if not isinstance(raw, Mapping) or not _REQUIRED_EXAMPLE_KEYS.issubset(raw):
            raise ValueError(
                f"eval set {path}: examples[{index}] must be a mapping carrying "
                "'input' and 'expected_output' (schema {input, expected_output, context})"
            )
        examples.append(dict(raw))
    return examples


def _read_template(template_path: Path, component: str) -> str:
    """Seed prompt = current content of the component's template file."""
    if not template_path.is_file():
        raise FileNotFoundError(
            f"prompt template for component {component!r} not found: "
            f"{template_path} (the template file is the deployment surface; "
            "create the seed prompt first)"
        )
    content = template_path.read_text(encoding="utf-8")
    if not content.strip():
        raise ValueError(
            f"prompt template for component {component!r} is empty: {template_path}"
        )
    return content


def _deterministic_mutation(
    base_prompt: str, notes: Mapping[str, str], generation: int, variant_index: int
) -> str:
    """Append the reflective notes as a ``Revision constraints`` section.

    The variant index parameterizes the mutation: constraints are listed in
    deterministic (example-id) order, and the priority constraint rotates per
    variant so each variant differs textually and semantically. The embedded
    ``(generation N, variant M)`` header keeps every candidate unique.
    """
    ordered = sorted(notes.items())
    lines = [
        base_prompt.rstrip(),
        "",
        f"## Revision constraints (generation {generation}, variant {variant_index})",
        "",
    ]
    if ordered:
        for example_id, note in ordered:
            lines.append(f"- [{example_id}] {note}")
        focus_id = ordered[(variant_index - 1) % len(ordered)][0]
        lines.append(
            f"- Priority for this variant: resolve [{focus_id}] first; the "
            "remaining constraints follow."
        )
    else:
        lines.append(
            "- Preserve the current output format exactly; tighten edge-case handling."
        )
        lines.append(
            f"- Re-verify every example against its labeled expected output "
            f"(variant focus #{variant_index})."
        )
    return "\n".join(lines)


def _model_rewrite(
    rewriter: Callable[[str], str],
    component: str,
    feedback: str,
    notes: Mapping[str, str],
    generation: int,
    variant_index: int,
    base_prompt: str,
) -> str | None:
    """Reflective rewrite via the injected model; None when unusable."""
    lines = [
        f"Revise the {component} prompt. Current failure digest:",
        feedback,
        "",
        "Reflective notes:",
        *(f"- [{example_id}] {note}" for example_id, note in sorted(notes.items())),
        f"(revision {generation}.{variant_index})",
    ]
    rewritten = rewriter("\n".join(lines))
    if not isinstance(rewritten, str) or not rewritten.strip():
        return None
    if rewritten == base_prompt:
        return None  # no progress: fall back to the deterministic mutation
    return rewritten


def _version_id_for(component: str, prompt: str) -> str:
    """Content-addressed version id for a deployed prompt (drift-registry hook)."""
    digest = hashlib.sha256(prompt.encode("utf-8")).hexdigest()[:12]
    return f"{component}-prompt-{digest}"


def _atomic_write_text(path: Path, content: str) -> None:
    """Write ``content`` to ``path`` atomically (tmp file + ``os.replace``)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f"{path.name}.{os.getpid()}.tmp")
    try:
        with open(tmp, "w", encoding="utf-8") as fh:
            fh.write(content)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    except OSError:
        tmp.unlink(missing_ok=True)
        raise


def _inside_dir(path: Path, root: Path) -> bool:
    """True when ``path`` lives inside ``root`` (audit-commit staging check)."""
    try:
        path.resolve().relative_to(root.resolve())
    except ValueError:
        return False
    return True
