"""hermes-v2 GEPARunner: weekly offline prompt optimization (plan P10.T5).

Orchestrates a GEPA-style optimization run over the memory subagent
components (plan Phase 10): for each component, the current prompt template
is the seed candidate, an optimization loop generates and evaluates prompt
variants, all evaluated candidates join the component's Pareto front
(:class:`~hermes.optimization.pareto.ParetoFrontStore`, plan P10.T4), and the
best candidate is DEPLOYED by writing it back to the prompt template file —
the template file IS the deployment surface; the pipeline reads it at cron
time (P10.T6). Every deployment is registered through the optional
``on_deploy`` hook (production wires it to
``ModelVersionRegistry.register(component, record.version_id,
eval_score=record.score, gepa_run_id=record.run_id)`` — the P19 drift
registry — and is committed to Git (``[gepa] deploy <component>
<generation> score=<s>``) when a :class:`~hermes.memory.git_backend.GitBackend`
over the optimization directory is supplied.

The OptimizationLoop (built-in GEPA-style loop)
----------------------------------------------
``gepa`` (gepa-ai/gepa) is an OPTIONAL dependency and is deliberately not
installed (same stance as the adapter mapping documented in
``hermes/optimization/adapters/__init__.py`` — availability is probed with
:func:`importlib.util.find_spec`, never imported). :meth:`GEPARunner.run_weekly`
is therefore backed by a self-contained, DETERMINISTIC implementation of the
same loop shape ("OptimizationLoop"): candidate variants are generated by
applying the adapter's ``make_reflective_dataset`` failure notes to the
current best prompt as appended ``## Revision constraints`` sections plus
parameterized mutations (rotating priority per variant); each variant is
evaluated via ``adapter.evaluate``; the top-K pool survives per generation;
the loop runs ``n_generations`` (default 3) x ``variants_per_generation``
(default 3) = 9 candidates + the seed. Swapping in the gepa library later —
or an LLM-backed reflective rewriter via ``model_factory`` — is an
implementation detail behind this loop interface: the adapters already
expose exactly the ``evaluate`` / ``make_reflective_dataset`` protocol gepa
drives (:class:`~hermes.optimization.adapters.GEPAAdapter`).

``model_factory(component) -> (reflective_text -> revised_prompt)`` is the
optional "reflection model" seam (the gepa reflection-LM role): when given,
its rewrite replaces the deterministic mutation for each variant, falling
back to the deterministic mutation when the model returns unusable output.

1-hour budget reasoning
-----------------------
The plan's acceptance criterion is "weekly run completes within 1 hour".
Structurally the run is bounded: 4 components x (3 generations x 3 variants
+ 1 seed) = 40 adapter evaluations over 55-example eval sets, plus one
reflection batch per generation (12 total). With the deterministic loop and
no model calls this is seconds of CPU; with an LLM-backed rewriter the
budget is dominated by 9 reflection calls per component — comfortably inside
an hour even at interactive latencies. The integration test
``test_completes_within_1_hour`` runs the full 4-component pipeline with
fake runners and asserts wall time < 60s (the structural bound), which is
the testable proxy for the 1-hour acceptance criterion.
"""

