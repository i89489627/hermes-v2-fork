"""ContextManager — detect/switch/create memory contexts (plan P5.T1).

Contexts scope the memory graph (plan Phase 5): the implicit ``global``
context plus named contexts under ``<memory-repo>/contexts/<name>/``
(directory presence = existence), matching the layout
:class:`hermes.memory.store.MemoryStore` uses (``<root>/global/facts/`` and
``<root>/contexts/<name>/facts/``). Parent/session metadata plus the
detection rule tables live in ``<root>/contexts.json`` (atomic writes:
temp file + ``os.replace``, last writer wins — the P1.T5 file lock serializes
store writes; context metadata updates are single-key replacements).

Detection precedence (documented): ``explicit`` (a ``/context switch`` this
session) > ``gateway_chat_id`` (gateway sessions) > ``cwd`` (CLI sessions) >
``"global"``. Rule-based lookups degrade to ``"global"`` on no match or on a
rule pointing at a deleted context — detection must never break session
start — while an ``explicit`` reference is validated and raises
:class:`UnknownContextError` (silently ignoring explicit user intent would
hide typos).

Session-boundary semantics (plan P5.T1 acceptance "switch reloads stable
context"): every :meth:`ContextManager.switch_context` call returns a freshly
rebuilt :class:`~hermes.memory.types.Context` object, and the stable context
(:class:`StableContext` — global ``MEMORY.md`` + context ``MEMORY.md``, what
the P4.T3 injector loads at session start) is a new frozen snapshot object
per :meth:`ContextManager.stable_context_snapshot` call, always reflecting
the current disk state. Callers switch and then rebuild the snapshot; nothing
is cached across the boundary.
"""

from __future__ import annotations

import json
import logging
import os
import re
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from hermes.config import hermes_home
from hermes.memory.types import Context

logger = logging.getLogger(__name__)

#: Directory holding named contexts under the memory-repo root (plan P5.T1;
#: aligned with ``hermes.memory.store.CONTEXTS_DIR``).
CONTEXTS_DIRNAME = "contexts"

#: Metadata file under the memory-repo root: parents, active sessions and
#: the ``cwd_rules`` / ``chat_rules`` detection tables.
METADATA_FILENAME = "contexts.json"

#: Name of the always-present root context (plan P5.T1/P5.T4).
GLOBAL_CONTEXT = "global"

#: Per-context index file name (``<root>/MEMORY.md`` is the global one,
#: regenerated by ``hermes.memory.store.MemoryStore``).
MEMORY_MD_NAME = "MEMORY.md"

#: Directory backing the implicit global context (aligned with the store).
GLOBAL_DIRNAME = "global"

#: Valid context names: lowercase slugs starting with [a-z0-9].
_NAME_PATTERN = re.compile(r"[a-z0-9][a-z0-9-]*")


class UnknownContextError(LookupError):
    """Raised for a context name that does not exist (switch/parent/explicit)."""


@dataclass(frozen=True)
class StableContext:
    """What gets loaded at session start (plan P4.T3/P5.T1).

    Two markdown documents: the global ``MEMORY.md`` (the store's global
    index) and the active context's ``MEMORY.md``. Frozen snapshot: a new
    object is built per call and always reflects current disk state — this is
    the "switch reloads stable context" session boundary.
    """

    context: str
    global_memory_md: str | None
    context_memory_md: str | None
    global_memory_md_path: Path
    context_memory_md_path: Path
    loaded_at: datetime


def _atomic_write(path: Path, content: str) -> None:
    """Write ``content`` to ``path`` atomically (unique temp + ``os.replace``)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    try:
        with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)  # pragma: no cover - no-op after successful replace


def _read_optional(path: Path) -> str | None:
    """File content or ``None`` when missing (never raises on read)."""
    try:
        return path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None


def _normalize_path(value: str) -> str:
    """Expand and normalize a path string to forward slashes (rule matching)."""
    return str(Path(value).expanduser()).replace("\\", "/").rstrip("/") or "/"


def _path_has_suffix(path: str, suffix: str) -> bool:
    """True when ``path`` ends with ``suffix`` on a path-segment boundary.

    ``"/a/mywork"`` must NOT match suffix ``"work"``; ``"/a/work"`` must. A
    suffix with a leading slash carries its own boundary (the slash), so
    plain ``endswith`` suffices there.
    """
    if not suffix:
        return False
    if path == suffix:
        return True
    if not path.endswith(suffix):
        return False
    if suffix.startswith("/"):
        return True
    return path[-len(suffix) - 1] == "/"


class ContextManager:
    """Detects, switches, creates and lists memory contexts (plan P5.T1)."""

    def __init__(self, repo_root: Path | None = None) -> None:
        self.root = Path(repo_root) if repo_root is not None else hermes_home() / "memory-repo"

    # ── metadata (contexts.json) ────────────────────────────────────────────

    def _metadata_path(self) -> Path:
        return self.root / METADATA_FILENAME

    def _load_metadata(self) -> dict[str, Any]:
        """Load contexts.json; missing or corrupt metadata yields ``{}``.

        A corrupt file is never fatal (detection/switching must survive a
        truncated write from a crashed process): it is logged and treated as
        empty, keeping the directory-presence semantics authoritative.
        """
        path = self._metadata_path()
        if not path.exists():
            return {}
        try:
            with open(path, encoding="utf-8") as fh:
                doc = json.load(fh)
        except (ValueError, OSError) as exc:
            logger.warning("contexts.json unreadable (%s); treating as empty", exc)
            return {}
        return doc if isinstance(doc, dict) else {}

    def _save_metadata(self, doc: dict[str, Any]) -> None:
        _atomic_write(self._metadata_path(), json.dumps(doc, indent=2, sort_keys=True) + "\n")

    def _context_entry(self, doc: dict[str, Any], name: str) -> dict[str, Any]:
        raw = doc.get("contexts")
        if isinstance(raw, dict):
            entry = raw.get(name)
            if isinstance(entry, dict):
                return entry
        return {}

    def _save_context_entry(self, name: str, entry: dict[str, Any]) -> None:
        doc = self._load_metadata()
        contexts = doc.setdefault("contexts", {})
        if not isinstance(contexts, dict):  # corrupt shape -> reset the section
            contexts = {}
            doc["contexts"] = contexts
        contexts[name] = entry
        self._save_metadata(doc)

    # ── context objects ─────────────────────────────────────────────────────

    def context_exists(self, name: str) -> bool:
        """True when ``name`` names a context (directory presence = existence)."""
        if name == GLOBAL_CONTEXT:
            return True  # implicit root: always exists (plan P5.T4 migration target)
        return (self.root / CONTEXTS_DIRNAME / name).is_dir()

    def _build_context(self, doc: dict[str, Any], name: str) -> Context:
        if name == GLOBAL_CONTEXT:
            path = self.root / GLOBAL_DIRNAME
            parent = None  # global is the root of the inheritance chain
        else:
            path = self.root / CONTEXTS_DIRNAME / name
            parent = self._context_entry(doc, name).get("parent")
        sessions_raw = self._context_entry(doc, name).get("active_sessions")
        return Context(
            name=name,
            parent=None if parent is None else str(parent),
            path=path,
            active_sessions=[str(session) for session in sessions_raw or []],
        )

    # ── detection (plan P5.T1: cwd / gateway chat id / explicit) ────────────

    def _cwd_rules(self, doc: dict[str, Any]) -> list[list[str]]:
        """``cwd_rules``: list of ``[path_suffix, context]`` pairs."""
        raw = doc.get("cwd_rules")
        if not isinstance(raw, list):
            return []
        rules: list[list[str]] = []
        for rule in raw:
            if isinstance(rule, (list, tuple)) and len(rule) == 2:
                rules.append([str(rule[0]), str(rule[1])])
            else:
                logger.warning("ignoring malformed cwd rule %r (expected [suffix, context])", rule)
        return rules

    def _chat_rules(self, doc: dict[str, Any]) -> dict[str, str]:
        """``chat_rules``: mapping of gateway chat id -> context name."""
        raw = doc.get("chat_rules")
        if not isinstance(raw, dict):
            return {}
        return {str(chat_id): str(context) for chat_id, context in raw.items()}

    def _resolve_rule_target(self, name: str) -> str:
        """Rule targets degrade to global when their context was deleted."""
        if self.context_exists(name):
            return name
        logger.warning("context rule points at missing context %r; falling back to global", name)
        return GLOBAL_CONTEXT

    def detect_context(self, session_metadata: dict[str, Any]) -> str:
        """Detect the active context from session metadata (plan P5.T1).

        Precedence: ``explicit`` > ``gateway_chat_id`` > ``cwd`` >
        ``"global"``. ``cwd`` matches the ``cwd_rules`` table
        (``[path_suffix, context]`` pairs, segment-boundary suffix match);
        ``gateway_chat_id`` looks up the ``chat_rules`` table. Missing keys
        and non-matching lookups fall back to ``"global"``; an ``explicit``
        name that does not exist raises :class:`UnknownContextError`.
        """
        explicit = session_metadata.get("explicit")
        if explicit is not None:
            name = str(explicit)
            if not self.context_exists(name):
                raise UnknownContextError(f"explicit context {name!r} does not exist")
            return name

        doc = self._load_metadata()

        chat_id = session_metadata.get("gateway_chat_id")
        if chat_id is not None:
            rules = self._chat_rules(doc)
            if str(chat_id) in rules:
                return self._resolve_rule_target(rules[str(chat_id)])
            return GLOBAL_CONTEXT

        cwd = session_metadata.get("cwd")
        if cwd is not None:
            normalized = _normalize_path(str(cwd))
            for suffix, context in self._cwd_rules(doc):
                if _path_has_suffix(normalized, _normalize_path(suffix)):
                    return self._resolve_rule_target(context)
            return GLOBAL_CONTEXT

        return GLOBAL_CONTEXT

    # ── switch / create / list ──────────────────────────────────────────────

    def switch_context(self, name: str, session_id: str | None = None) -> Context:
        """Switch to ``name`` and return a freshly rebuilt context snapshot.

        Session-boundary semantics: the returned
        :class:`~hermes.memory.types.Context` is a new object built from
        current disk state on every call; the caller rebuilds the stable
        context via :meth:`stable_context_snapshot` after switching (the P4.T3
        injector reloads it at this boundary). With ``session_id`` the session
        is recorded in the context's ``active_sessions`` (idempotent, atomic
        metadata write). Unknown names raise :class:`UnknownContextError`.
        """
        if not self.context_exists(name):
            raise UnknownContextError(f"context {name!r} does not exist")
        if session_id is not None:
            self.record_session(name, str(session_id))
        return self._build_context(self._load_metadata(), name)

    def record_session(self, name: str, session_id: str) -> None:
        """Append ``session_id`` to ``name``'s ``active_sessions`` (idempotent)."""
        entry = self._context_entry(self._load_metadata(), name)
        sessions = [str(session) for session in entry.get("active_sessions") or []]
        if session_id in sessions:
            return
        sessions.append(session_id)
        entry["active_sessions"] = sessions
        entry.setdefault("parent", None)
        self._save_context_entry(name, entry)

    def create_context(self, name: str, parent: str | None = None) -> Context:
        """Create a named context (mkdir + metadata update) and return it.

        ``name`` must be a lowercase slug (``[a-z0-9][a-z0-9-]*``) and must
        not already exist; ``parent`` (when given) must be an existing
        context — ``"global"`` is the usual root of the inheritance chain
        (plan P5.T1: contexts inherit global facts through their parent).
        """
        if not _NAME_PATTERN.fullmatch(name):
            raise ValueError(
                f"context name {name!r} must be a lowercase slug matching [a-z0-9][a-z0-9-]*"
            )
        if name == GLOBAL_CONTEXT:
            raise ValueError(
                f"{GLOBAL_CONTEXT!r} is the implicit root context and cannot be created"
            )
        if parent is not None:
            parent = str(parent)
            if parent == name:
                raise ValueError(f"context {name!r} cannot be its own parent")
            if not self.context_exists(parent):
                raise UnknownContextError(f"parent context {parent!r} does not exist")
        context_dir = self.root / CONTEXTS_DIRNAME / name
        try:
            context_dir.mkdir(parents=True, exist_ok=False)
        except FileExistsError as exc:
            raise ValueError(f"context {name!r} already exists") from exc
        self._save_context_entry(name, {"parent": parent, "active_sessions": []})
        logger.info("context %r created (parent=%s)", name, parent)
        return Context(name=name, parent=parent, path=context_dir, active_sessions=[])

    def list_contexts(self) -> list[Context]:
        """All contexts, sorted by name; ``global`` is always included."""
        doc = self._load_metadata()
        names = {GLOBAL_CONTEXT}
        contexts_root = self.root / CONTEXTS_DIRNAME
        if contexts_root.is_dir():
            names.update(path.name for path in contexts_root.iterdir() if path.is_dir())
        return [self._build_context(doc, name) for name in sorted(names)]

    # ── stable context (session-start load) ────────────────────────────────

    def stable_context_snapshot(self, name: str) -> StableContext:
        """Fresh stable-context snapshot for ``name`` (plan P5.T1 session boundary).

        Reads both documents from disk at call time — global ``MEMORY.md``
        plus the context's own ``MEMORY.md`` — and returns a new frozen
        :class:`StableContext`; nothing is cached, so switching contexts and
        re-snapshotting reloads the stable context (see the module docstring).
        """
        if not self.context_exists(name):
            raise UnknownContextError(f"context {name!r} does not exist")
        global_path = self.root / MEMORY_MD_NAME
        context_path = self.root / CONTEXTS_DIRNAME / name / MEMORY_MD_NAME
        return StableContext(
            context=name,
            global_memory_md=_read_optional(global_path),
            context_memory_md=_read_optional(context_path),
            global_memory_md_path=global_path,
            context_memory_md_path=context_path,
            loaded_at=datetime.now(UTC),
        )
